// The hosted app compiler installs every declared dependency inside one Worker isolate, and
// React plus the MCP SDK exceeded its memory limit. The UI therefore ships prebuilt: React is
// bundled here, and only framework imports stay for the host's browser build to resolve.
import { readFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const target = join(root, "ui/main.js");
const result = await Bun.build({
  entrypoints: [join(root, "ui/main.tsx")],
  format: "esm",
  target: "browser",
  minify: true,
  external: ["apps", "apps/*", "*.css"],
  define: { "process.env.NODE_ENV": '"production"' },
  plugins: [
    {
      name: "ui-build-react",
      setup(build) {
        // React is installed beside this script, not in the app package.
        build.onResolve({ filter: /^(react|react-dom|scheduler)(\/.*)?$/ }, (args) => ({
          path: Bun.resolveSync(args.path, import.meta.dir),
        }));
      },
    },
  ],
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const [output] = result.outputs;
if (output === undefined || result.outputs.length !== 1) throw new Error("Expected one UI bundle");
const built = `// Generated by ui-build/build.ts from ui/*.tsx; do not edit.\n${await output.text()}`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== built) {
    console.error("ui/main.js is stale; run bun ui-build/build.ts");
    process.exit(1);
  }
} else await Bun.write(target, built);
console.log(`ui/main.js ${built.length} bytes`);
